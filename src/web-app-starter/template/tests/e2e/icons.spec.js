const { test, expect } = require('@playwright/test');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { deleteUser, confirmDelete } = require('../settings-helper');

test('実Storageでユーザーアイコンを登録・変更・削除し各画面に表示する', async ({ page }, info) => {
  const name = `画像ユーザー-${randomUUID().slice(0, 6)}`;
  const sample = path.join(__dirname, '../fixtures/sample.png');
  let iconUrl;
  try {
    await page.goto('/admin/users');
    await page.getByLabel('投稿者名', { exact: false }).fill(name);
    await page.getByRole('button', { name: '追加して選択', exact: true }).click();
    const edit = page.getByRole('link', { name: `${name}のアイコンを変更`, exact: true });
    const editUrl = await edit.getAttribute('href');
    iconUrl = editUrl.replace('/edit', '');
    await edit.click();
    await page.getByLabel('アイコン画像', { exact: true }).setInputFiles(sample);
    const preview = page.getByAltText('新しいアイコンのプレビュー');
    await expect(preview).toBeVisible();
    await expect.poll(() => preview.evaluate(img => img.complete && img.naturalWidth > 0)).toBeTruthy();
    await page.getByRole('button', { name: 'アイコンを保存' }).click();
    await expect(page.getByRole('status')).toHaveText('アイコンを保存しました。');
    await expect.poll(() => page.locator('[data-current-avatar] img').evaluate(img => img.complete && img.naturalWidth === 256)).toBeTruthy();
    expect((await page.request.get(iconUrl)).status()).toBe(200);
    expect((await page.request.post(`${iconUrl}/delete`)).status()).toBe(403);
    await page.goto('/posts/new');
    await page.locator('.ui-user-trigger').click();
    const popup = page.getByRole('dialog', { name: 'ユーザーを切り替え' });
    await expect(popup.getByRole('button', { name: `${name} 選択中` }).locator('img')).toBeVisible();
    await page.screenshot({ path: info.outputPath('icon-popup.png'), animations: 'disabled' });
    await page.keyboard.press('Escape');
    await page.goto(editUrl);
    await page.getByLabel('アイコン画像', { exact: true }).setInputFiles({ name: 'bad.png', mimeType: 'image/png', buffer: Buffer.from('not an image') });
    await page.getByRole('button', { name: 'アイコンを保存' }).click();
    await expect(page.getByRole('alert').first()).toContainText('JPEG');
    expect((await page.request.get(iconUrl)).status()).toBe(200);
    await page.getByLabel('アイコン画像', { exact: true }).setInputFiles(sample);
    await page.getByRole('button', { name: 'アイコンを保存' }).click();
    await expect(page.getByRole('status')).toHaveText('アイコンを保存しました。');
    await page.goto(editUrl);
    await page.setViewportSize({ width: 390, height: 844 });
    await expect.poll(() => page.locator('.ui-profile-avatar img').evaluate(img => img.complete && img.naturalWidth === 256)).toBeTruthy();
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
    await page.screenshot({ path: info.outputPath('icon-edit-mobile.png'), fullPage: true, animations: 'disabled' });
    await page.getByText('アイコンを削除する', { exact: true }).click();
    await page.getByRole('button', { name: 'アイコンを削除', exact: true }).click();
    await confirmDelete(page);
    await expect(page.getByRole('status')).toHaveText('アイコンを削除しました。');
    expect((await page.request.get(iconUrl)).status()).toBe(404);
  } finally { await deleteUser(page, name); }
});
